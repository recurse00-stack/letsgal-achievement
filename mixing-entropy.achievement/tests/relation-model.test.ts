test('spring simulation pulls connected nodes, damps to rest, avoids coincident nodes and preserves camera anchors',()=>{
 const data=buildRelations(fixture(),'a'),points=graphPositions(data);
 for(let i=0;i<450;i++)stepGraph(data,points);
 const held=relationId('stage','a','unknown'),neighbor=relationId('default','unknown'),start={...points[neighbor]};
 points[held].x+=140;points[held].y-=90;
 for(let i=0;i<18;i++)stepGraph(data,points,held);
 assert.ok(Math.hypot(points[neighbor].x-start.x,points[neighbor].y-start.y)>5,'connected node follows the dragged node');
 points[held].hx=points[held].x;points[held].hy=points[held].y;
 let speed=0;for(let i=0;i<800;i++)speed=stepGraph(data,points);
 assert.ok(speed<.03,`settles instead of perpetual shaking: ${speed}`);
 assert.ok(Object.values(points).every(p=>Number.isFinite(p.x+p.y)&&Math.abs(p.x)<10000));
 const fitted=fitGraph(points),zoomed=zoomGraph(fitted,1.2,250,200);
 assert.ok(Math.abs((250-fitted.x)/fitted.scale-(250-zoomed.x)/zoomed.scale)<1e-8);
 const a=data.nodes[0].id,b=data.nodes[1].id;points[a].x=points[b].x;points[a].y=points[b].y;stepGraph(data,points);assert.ok(Math.hypot(points[a].x-points[b].x,points[a].y-points[b].y)>.01);
});
