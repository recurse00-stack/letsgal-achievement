test('relation graph shares scheme/interface identities, follows effective surfaces and excludes removed stages',()=>{
 const input=fixture();input.catalog.stages=[{...presetStages('a')[1]},{...presetStages('a')[2],levelMode:'custom',levelId:'gold'},{...presetStages('a')[0],disabled:true}];
 const expanded=[relationId('card','a','unknown'),relationId('card','a','revealed'),relationId('level-part','a','revealed'),relationId('popup','a','revealed')];
 const graph=buildRelations(input,'a',expanded);
 assert.ok(!graph.nodes.some(n=>n.id===relationId('stage','a','hidden')));
 assert.equal(graph.nodes.filter(n=>n.id===relationId('scheme','card','card')).length,1);
 assert.equal(graph.edges.filter(e=>e.to===relationId('scheme','card','card')&&e.label==='默认方案').length,2);
 assert.ok(graph.edges.some(e=>e.from===relationId('level-part','a','revealed')&&e.to===relationId('level','gold')));
 assert.ok(!graph.edges.some(e=>e.from===relationId('stage','a','revealed')&&e.label==='沿用内容'));
 assert.ok(graph.nodes.some(n=>n.id===relationId('interface','mixing-entropy.achievement/special')));
 const refs=relationReferrers(input,relationId('scheme','card','card'));
 assert.deepEqual(refs.map(r=>r.achievementId+'/'+r.stageId),['a/unknown','a/revealed','b/hidden','b/unknown','b/revealed']);
 const more=buildRelations(input,'a',expanded,0,refs,relationId('scheme','card','card'));
 assert.equal(more.nodes.filter(n=>n.id===relationId('achievement','b')).length,1);
 const collapsed=buildRelations(input,'a',[],0,refs,relationId('scheme','card','card'));
 assert.ok(!collapsed.nodes.some(n=>n.id===relationId('achievement','b')),'collapsed sources leave no orphan reference nodes');
});
